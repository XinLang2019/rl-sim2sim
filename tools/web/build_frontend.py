#!/usr/bin/env python3
"""Bundle the native JS modules without Node or external build dependencies.

The single script entry also works with the preceding server's static whitelist.
"""
from pathlib import Path

MODULES = ('core', 'service', 'telemetry', 'csv_import', 'renderer', 'screen_recording', 'controller', 'resources', 'chart_layout', 'chart_interaction', 'charts', 'charts_editor', 'logs', 'joystick', 'robot_reset', 'recordings', 'output_settings', 'app')

def build():
    frontend = Path(__file__).resolve().parent / 'frontend'
    parts = ['// Generated by python3 tools/web/build_frontend.py; edit modules/, then rebuild.\n', (frontend / 'modules/appearance.js').read_text(),
             '\ndocument.addEventListener(\"DOMContentLoaded\", () => {\n']
    for name in MODULES:
        parts.append('\n// module: ' + name + '\n' + (frontend / 'modules' / (name + '.js')).read_text())
    parts.append('\n}, {once: true});\n')
    (frontend / 'app.js').write_text(''.join(parts))

if __name__ == '__main__':
    build()
